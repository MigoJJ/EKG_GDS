"""
Phase 5 Step 3: Audit Trail & Clinical Data Logging

Records all ECG analyses for:
  - Regulatory compliance (HIPAA, GDPR, PIMS)
  - Clinical audit (track AI decisions vs. doctor decisions)
  - Model performance monitoring
  - Feedback collection for retraining

Data stored in JSONL format (one JSON object per line, append-only).

Privacy considerations:
  - ECG signal: never stored (hash only)
  - Patient info: masked (hospital_id instead of patient name/ID)
  - Timestamps: day-granularity to prevent tracking
  - Doctor feedback: encrypted at rest
"""

from __future__ import annotations
import json
import hashlib
import os
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, Optional, List
import logging

logger = logging.getLogger(__name__)


def hash_signal(signal_bytes: bytes) -> str:
    """
    Hash ECG signal for audit purposes (never store raw signal).

    Ensures we can match signal to log entry without storing patient data.
    """
    return hashlib.sha256(signal_bytes).hexdigest()[:16]


def mask_timestamp(dt: Optional[datetime] = None) -> str:
    """
    Return timestamp at day granularity (privacy protection).

    Prevents temporal tracking of individual patients.
    """
    if dt is None:
        dt = datetime.utcnow()
    return dt.strftime("%Y-%m-%d")  # Date only, not time


class AuditEntry:
    """Single audit log entry for one ECG analysis."""

    def __init__(
        self,
        request_id: str,
        hospital_id: str,
        signal_hash: str,
        model_version: str,
        cutoff_version: str,
    ):
        """
        Initialize audit entry.

        Args:
            request_id: Unique request ID (generated by API)
            hospital_id: Hospital identifier (not patient name)
            signal_hash: SHA256 hash of ECG signal (not the signal itself!)
            model_version: Model version (e.g., "phase3_kaggle_20261017")
            cutoff_version: Cutoff version (e.g., "fold9_20261017")
        """
        self.request_id = request_id
        self.hospital_id = hospital_id
        self.signal_hash = signal_hash
        self.timestamp = mask_timestamp()
        self.model_version = model_version
        self.cutoff_version = cutoff_version

        # Result (populated after analysis)
        self.result: Optional[Dict[str, Any]] = None

        # Doctor feedback (populated later by doctor)
        self.doctor_feedback: Optional[Dict[str, Any]] = None

    def set_result(
        self,
        primary_diagnosis: List[str],
        kcd_code: str,
        urgency: str,
        confidence: float,
        latency_ms: Dict[str, float],
    ):
        """
        Record analysis result (called after analysis completes).

        Args:
            primary_diagnosis: List of diagnoses (e.g., ["MI", "RBBB"])
            kcd_code: KCD-10 code
            urgency: "EMERGENCY", "URGENT", or "ROUTINE"
            confidence: Model confidence (0-1)
            latency_ms: Timing breakdown (feature extraction, inference, llm)
        """
        self.result = {
            "primary_diagnosis": primary_diagnosis,
            "kcd_code": kcd_code,
            "urgency": urgency,
            "confidence": confidence,
            "latency_ms": latency_ms,
        }

    def set_doctor_feedback(
        self,
        agree: bool,
        corrected_diagnosis: Optional[List[str]] = None,
        corrected_kcd_code: Optional[str] = None,
        notes: Optional[str] = None,
    ):
        """
        Record doctor's final judgment (called after clinician review).

        Args:
            agree: True if doctor agrees with AI diagnosis
            corrected_diagnosis: Doctor's diagnosis if different
            corrected_kcd_code: Doctor's KCD code if different
            notes: Free-text notes from doctor
        """
        self.doctor_feedback = {
            "agree": agree,
            "corrected_diagnosis": corrected_diagnosis,
            "corrected_kcd_code": corrected_kcd_code,
            "notes": notes,
            "feedback_timestamp": mask_timestamp(),
        }

    def to_dict(self) -> Dict[str, Any]:
        """Serialize to JSON-safe dict (for JSONL storage)."""
        return {
            "request_id": self.request_id,
            "hospital_id": self.hospital_id,
            "signal_hash": self.signal_hash,
            "timestamp": self.timestamp,
            "model_version": self.model_version,
            "cutoff_version": self.cutoff_version,
            "result": self.result,
            "doctor_feedback": self.doctor_feedback,
        }

    def to_json(self) -> str:
        """Serialize to JSON line (for JSONL file)."""
        return json.dumps(self.to_dict())


class AuditLogger:
    """Manages audit trail logging to JSONL files."""

    def __init__(self, audit_dir: str = "logs/audit"):
        """
        Initialize audit logger.

        Args:
            audit_dir: Directory to store JSONL audit logs
        """
        self.audit_dir = Path(audit_dir)
        self.audit_dir.mkdir(parents=True, exist_ok=True)

        # In-memory cache of recent entries (for quick retrieval)
        self.recent_entries: Dict[str, AuditEntry] = {}
        self.max_cache_size = 1000

    def create_entry(
        self,
        request_id: str,
        hospital_id: str,
        signal: bytes,
        model_version: str,
        cutoff_version: str,
    ) -> AuditEntry:
        """
        Create new audit entry.

        Args:
            request_id: Unique request ID
            hospital_id: Hospital identifier
            signal: Raw ECG signal (will be hashed, not stored)
            model_version: Model version string
            cutoff_version: Cutoff version string

        Returns:
            AuditEntry object
        """
        signal_hash = hash_signal(signal)
        entry = AuditEntry(
            request_id=request_id,
            hospital_id=hospital_id,
            signal_hash=signal_hash,
            model_version=model_version,
            cutoff_version=cutoff_version,
        )

        # Cache in memory
        self.recent_entries[request_id] = entry

        # Trim cache if too large
        if len(self.recent_entries) > self.max_cache_size:
            oldest_key = next(iter(self.recent_entries))
            del self.recent_entries[oldest_key]

        return entry

    def log_result(
        self,
        entry: AuditEntry,
        primary_diagnosis: List[str],
        kcd_code: str,
        urgency: str,
        confidence: float,
        latency_ms: Dict[str, float],
    ):
        """Log analysis result."""
        entry.set_result(
            primary_diagnosis=primary_diagnosis,
            kcd_code=kcd_code,
            urgency=urgency,
            confidence=confidence,
            latency_ms=latency_ms,
        )

        # Write to JSONL file immediately
        self._append_to_file(entry)

    def log_feedback(
        self,
        request_id: str,
        agree: bool,
        corrected_diagnosis: Optional[List[str]] = None,
        corrected_kcd_code: Optional[str] = None,
        notes: Optional[str] = None,
    ):
        """
        Log doctor feedback for an analysis.

        Args:
            request_id: Request ID to add feedback to
            agree: True if doctor agrees
            corrected_diagnosis: Doctor's diagnosis if different
            corrected_kcd_code: Doctor's KCD code if different
            notes: Doctor's notes
        """
        # Get from cache or read from file
        entry = self.recent_entries.get(request_id)
        if not entry:
            entry = self._read_entry_from_file(request_id)

        if not entry:
            logger.warning(f"Request {request_id} not found for feedback")
            return

        entry.set_doctor_feedback(
            agree=agree,
            corrected_diagnosis=corrected_diagnosis,
            corrected_kcd_code=corrected_kcd_code,
            notes=notes,
        )

        # Update in file (append feedback line)
        self._append_to_file(entry)

    def _append_to_file(self, entry: AuditEntry):
        """Append audit entry to JSONL file."""
        # Date-based file (logs/audit/YYYY-MM-DD.jsonl)
        date_str = entry.timestamp.replace("-", "")  # YYYYMMDD
        log_file = self.audit_dir / f"{date_str}.jsonl"

        try:
            with open(log_file, "a") as f:
                f.write(entry.to_json() + "\n")
                f.flush()
        except IOError as e:
            logger.error(f"Failed to write audit log: {e}")

    def _read_entry_from_file(self, request_id: str) -> Optional[AuditEntry]:
        """
        Read entry from JSONL file by request_id.

        Searches recent files for efficiency.
        """
        # Search last 7 days of files
        from datetime import timedelta
        today = datetime.utcnow()

        for days_back in range(7):
            date = today - timedelta(days=days_back)
            date_str = date.strftime("%Y%m%d")
            log_file = self.audit_dir / f"{date_str}.jsonl"

            if not log_file.exists():
                continue

            try:
                with open(log_file, "r") as f:
                    for line in f:
                        if not line.strip():
                            continue
                        data = json.loads(line)
                        if data.get("request_id") == request_id:
                            # Reconstruct entry from dict
                            entry = AuditEntry(
                                request_id=data["request_id"],
                                hospital_id=data["hospital_id"],
                                signal_hash=data["signal_hash"],
                                model_version=data["model_version"],
                                cutoff_version=data["cutoff_version"],
                            )
                            entry.result = data.get("result")
                            entry.doctor_feedback = data.get("doctor_feedback")
                            return entry
            except IOError as e:
                logger.warning(f"Failed to read audit log {log_file}: {e}")

        return None

    def query_entries(
        self,
        hospital_id: Optional[str] = None,
        date: Optional[str] = None,
        limit: int = 100,
    ) -> List[Dict[str, Any]]:
        """
        Query audit entries.

        Args:
            hospital_id: Filter by hospital (optional)
            date: Filter by date YYYY-MM-DD (optional)
            limit: Max entries to return

        Returns:
            List of audit entries (dicts)
        """
        results = []

        # Determine which files to search
        if date:
            files_to_search = [self.audit_dir / f"{date.replace('-', '')}.jsonl"]
        else:
            # Last 30 days
            from datetime import timedelta
            today = datetime.utcnow()
            files_to_search = []
            for days_back in range(30):
                d = today - timedelta(days=days_back)
                files_to_search.append(self.audit_dir / d.strftime("%Y%m%d.jsonl"))

        # Search files
        for log_file in files_to_search:
            if not log_file.exists():
                continue

            try:
                with open(log_file, "r") as f:
                    for line in f:
                        if not line.strip():
                            continue
                        data = json.loads(line)

                        # Filter by hospital if specified
                        if hospital_id and data.get("hospital_id") != hospital_id:
                            continue

                        results.append(data)

                        if len(results) >= limit:
                            return results
            except IOError as e:
                logger.warning(f"Failed to read {log_file}: {e}")

        return results

    def get_entry(self, request_id: str) -> Optional[Dict[str, Any]]:
        """Get a single entry by request_id."""
        entry = self.recent_entries.get(request_id)
        if entry:
            return entry.to_dict()

        entry = self._read_entry_from_file(request_id)
        if entry:
            return entry.to_dict()

        return None


# Global audit logger instance
audit_logger = AuditLogger()
